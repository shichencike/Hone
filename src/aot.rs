// aot.rs - hone build --exe -c 的 AOT 编译：脚本 → C 中间文件 → 原生可执行文件
// 架构：
//   1. RUNTIME_C：内嵌的 C 运行时（boxed 值模型 HnValue + 引用计数 + 异常 setjmp/longjmp + 核心内置）
//   2. generate()：把 Hone AST 翻译成调用该运行时的 C 代码（含 main()）
//   3. 编译：find_cc() 定位 gcc/clang/cc，-Os -ffunction-sections + 链接期死代码消除 → 几十 KB 级体积
// 值语义与解释器一致：int/float/bool 内嵌；str/list/dict 引用计数（变量读取深拷贝，保持拷贝语义）；
//   函数按值传参；lambda 按值捕获；列表索引赋值克隆写回。
// 约定：所有 hn_* 构造函数返回"拥有"值（引用已计），调用方负责 hn_release_v；
//       表达式求值结果均为拥有值；变量读取返回 hn_copy（深拷贝）。

