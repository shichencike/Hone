impl AotGen {
    /// 生成表达式：返回求值为 owned HnValue 的 C 表达式。
    /// 约定：二元/比较/索引等操作函数消费其参数（生成器直接嵌套，无需手动释放临时值）。
    fn gen_expr(&mut self, e: &Expr) -> Result<String, ZError> {
        match e {
            Expr::IntLit(v, _) => Ok(format!("hn_int({})", v)),
            Expr::FloatLit(v, _) => {
                let s = v.to_string();
                let lit = if s.contains('.') || s.contains('e') || s.contains('E') {
                    s
                } else {
                    format!("{}.0", s)
                };
                Ok(format!("hn_float({})", lit))
            }
            Expr::BoolLit(b, _) => Ok(if *b { "hn_bool(true)".to_string() } else { "hn_bool(false)".to_string() }),
            Expr::StrLit(s, _) => Ok(format!("hn_str({})", c_str_lit(s))),
            Expr::Ident { name, span } => {
                if let Some(v) = self.lookup(name) {
                    Ok(format!("hn_copy({})", v))
                } else {
                    // 可能是模块函数名被当作值使用（如 print）——解释器报 undefined variable
                    Err(zerr(
                        &self.file,
                        &self.src,
                        codes::UNDEFINED,
                        format!("undefined variable `{}`", name),
                        *span,
                        Some("声明后再读取变量"),
                    ))
                }
            }
            Expr::ListLit(items, _) => {
                let mut parts = Vec::new();
                for it in items {
                    parts.push(self.gen_expr(it)?);
                }
                let mut s = String::from("({ HnValue _l = hn_list_new();");
                for p in parts {
                    s.push_str(&format!(" hn_list_push(_l, {});", p));
                }
                s.push_str(" _l; })");
                Ok(s)
            }
            Expr::DictLit(entries, _) => {
                let mut s = String::from("({ HnValue _d = hn_dict_new();");
                for (k, v) in entries {
                    let ve = self.gen_expr(v)?;
                    s.push_str(&format!(" hn_dict_set(_d, {}, {});", c_str_lit(k), ve));
                }
                s.push_str(" _d; })");
                Ok(s)
            }
            Expr::ListComp { elem, var, var2, iter, cond, span } => {
                self.gen_comp(elem, None, var, var2, iter, cond, true, *span)
            }
            Expr::DictComp { key, value, var, var2, iter, cond, span } => {
                self.gen_comp(key, Some(value), var, var2, iter, cond, false, *span)
            }
            Expr::FStr(segs, _) => {
                // 逐段拼接：hn_add_v(hn_str(lit), hn_to_str_v(code)) 链式
                let mut parts: Vec<String> = Vec::new();
                for seg in segs {
                    match seg {
                        FStrSeg::Lit(s) => parts.push(format!("hn_str({})", c_str_lit(s))),
                        FStrSeg::Code(c) => {
                            let ce = self.gen_expr(c)?;
                            parts.push(format!("hn_to_str_v({})", ce));
                        }
                    }
                }
                if parts.is_empty() {
                    return Ok("hn_str(\"\")".to_string());
                }
                let mut s = parts[0].clone();
                for p in parts.iter().skip(1) {
                    s = format!("hn_add_v({}, {})", s, p);
                }
                Ok(s)
            }
            Expr::Field { obj, field, span } => {
                let o = self.gen_expr(obj)?;
                Ok(format!("hn_field_v({}, {})", o, c_str_lit(field)))
            }
            Expr::OptionalField { obj, field, span } => {
                let o = self.gen_expr(obj)?;
                Ok(format!(
                    "({{ HnValue _o = {}; HnValue _r; if (_o.type == HN_NULL) {{ _r = hn_null(); hn_free_value(_o); }} else {{ _r = hn_field_v(_o, {}); }} _r; }})",
                    o,
                    c_str_lit(field)
                ))
            }
            Expr::Index { obj, index, span } => {
                let o = self.gen_expr(obj)?;
                let i = self.gen_expr(index)?;
                Ok(format!("hn_index_v({}, {})", o, i))
            }
            Expr::Unary { op, expr, span } => {
                let x = self.gen_expr(expr)?;
                Ok(match op {
                    UnOp::Neg => format!("hn_neg_v({})", x),
                    UnOp::Not => format!("hn_not_v({})", x),
                })
            }
            Expr::Binary { op, lhs, rhs, span } => {
                let l = self.gen_expr(lhs)?;
                let r = self.gen_expr(rhs)?;
                Ok(match op {
                    BinOp::Add => format!("hn_add_v({}, {})", l, r),
                    BinOp::Sub => format!("hn_sub_v({}, {})", l, r),
                    BinOp::Mul => format!("hn_mul_v({}, {})", l, r),
                    BinOp::Div => format!("hn_div_v({}, {})", l, r),
                    BinOp::Mod => format!("hn_mod_v({}, {})", l, r),
                    BinOp::Eq => format!("hn_eq_v({}, {})", l, r),
                    BinOp::Ne => format!("hn_ne_v({}, {})", l, r),
                    BinOp::Lt => format!("hn_lt_v({}, {})", l, r),
                    BinOp::Le => format!("hn_le_v({}, {})", l, r),
                    BinOp::Gt => format!("hn_gt_v({}, {})", l, r),
                    BinOp::Ge => format!("hn_ge_v({}, {})", l, r),
                    // 短路：lhs 决定是否求值 rhs
                    BinOp::And => format!(
                        "({{ HnValue _l = {}; HnValue _r = hn_is_true(_l) ? {} : hn_bool(false); hn_free_value(_l); _r; }})",
                        l, r
                    ),
                    BinOp::Or => format!(
                        "({{ HnValue _l = {}; HnValue _r = hn_is_true(_l) ? hn_bool(true) : {}; hn_free_value(_l); _r; }})",
                        l, r
                    ),
                    BinOp::Coalesce => format!(
                        "({{\n  HnValue _l = {};\n  HnValue _r;\n  if (_l.type == HN_NULL) {{ _r = {}; }}\n  else {{ _r = _l; }}\n  _r;\n}})",
                        l, r
                    ),
                })
            }
            Expr::Call { callee, args, span } => self.gen_call(callee, args, *span),
            Expr::Match { value, arms, span } => {
                let v = self.gen_expr(value)?;
                let mut s = String::from("({ HnValue _m = ");
                s.push_str(&v);
                s.push_str("; HnValue _r;\n");
                // 模式比较链：模式 → 分支体（模式为 None 表示 _ 通配符，作默认）
                let mut done = false;
                let mut indent = String::from("  ");
                for (pat, body) in arms {
                    let be = self.gen_expr(body)?;
                    match pat {
                        Some(p) => {
                            let pe = self.gen_expr(p)?;
                            s.push_str(&format!("{}if (hn_eq_raw(_m, {})) {{ _r = {}; }}\n", indent, pe, be));
                        }
                        None => {
                            s.push_str(&format!("{}else {{ _r = {}; }}\n", indent, be));
                            done = true;
                        }
                    }
                }
                if !done {
                    s.push_str(&format!("{}else {{ _r = hn_null(); }}\n", indent));
                }
                s.push_str("  hn_free_value(_m); _r; })");
                Ok(s)
            }
            Expr::IncDec { op, prefix, name, span } => {
                let v = self.lookup(name).ok_or_else(|| {
                    zerr(
                        &self.file,
                        &self.src,
                        codes::UNDEFINED,
                        format!("undefined variable `{}`", name),
                        *span,
                        Some("声明后再自增/自减"),
                    )
                })?;
                let f = match op {
                    IncOp::Inc => "hn_add_v",
                    IncOp::Dec => "hn_sub_v",
                };
                if *prefix {
                    Ok(format!(
                        "({{\n  HnValue _n = {}(hn_copy({}), hn_int(1));\n  hn_free_value({});\n  {} = _n;\n  hn_copy({});\n}})",
                        f, v, v, v, v
                    ))
                } else {
                    Ok(format!(
                        "({{\n  HnValue _o = hn_copy({});\n  HnValue _n = {}(hn_copy({}), hn_int(1));\n  hn_free_value({});\n  {} = _n;\n  _o;\n}})",
                        v, f, v, v, v
                    ))
                }
            }
            Expr::Ternary { cond, then_expr, else_expr, span } => {
                let c = self.gen_expr(cond)?;
                let t = self.gen_expr(then_expr)?;
                let e2 = self.gen_expr(else_expr)?;
                Ok(format!(
                    "({{\n  HnValue _c = {};\n  HnValue _r = hn_is_true(_c) ? {} : {};\n  hn_free_value(_c);\n  _r;\n}})",
                    c, t, e2
                ))
            }
            Expr::Lambda { params, body, span } => self.gen_lambda(params, body, *span),
        }
    }

    /// 推导式生成：is_list=true 时输出列表（elem 为元素），否则输出字典（elem 为键、value 为值）
    #[allow(clippy::too_many_arguments)]
    fn gen_comp(
        &mut self,
        elem: &Expr,
        value: Option<&Expr>,
        var: &str,
        var2: &Option<String>,
        iter: &Expr,
        cond: &Option<Box<Expr>>,
        is_list: bool,
        span: Span,
    ) -> Result<String, ZError> {
        let it = self.gen_expr(iter)?;
        // 循环变量名（每次迭代重新赋值；continue 无泄漏）
        let vv = format!("v{}", self.var_counter);
        self.var_counter += 1;
        let vv2 = format!("v{}", self.var_counter);
        self.var_counter += 1;
        let out_name = if is_list { "_l" } else { "_d" };
        let new_out = if is_list { "hn_list_new()" } else { "hn_dict_new()" };
        let mut s = String::new();
        s.push_str(&format!("({{\n  HnValue {} = {};\n", out_name, new_out));
        s.push_str(&format!("  HnValue _it = {};\n", it));
        s.push_str(&format!("  HnValue {} = hn_null();\n", vv));
        if var2.is_some() {
            s.push_str(&format!("  HnValue {} = hn_null();\n", vv2));
        }
        s.push_str("  if (_it.type == HN_LIST) {\n");
        s.push_str("    for (int _i = 0; _i < _it.as.list->len; _i++) {\n");
        s.push_str(&format!("      hn_free_value({});\n", vv));
        s.push_str(&format!("      {} = hn_copy(_it.as.list->items[_i]);\n", vv));
        self.scopes.push(HashMap::new());
        self.scopes.last_mut().expect("scope").insert(var.to_string(), vv.clone());
        if let Some(v2) = var2 {
            self.scopes.last_mut().expect("scope").insert(v2.clone(), vv2.clone());
        }
        let elem_c = self.gen_expr(elem)?;
        let val_c = match value {
            Some(v) => self.gen_expr(v)?,
            None => String::new(),
        };
        let cond_c = match cond {
            Some(c) => {
                let ce = self.gen_expr(c)?;
                format!("if (hn_truthy({})) ", ce)
            }
            None => String::new(),
        };
        if is_list {
            s.push_str(&format!("      {}hn_list_push(_l, {});\n", cond_c, elem_c));
        } else {
            s.push_str(&format!("      {}hn_dict_set_v(_d, {}, {});\n", cond_c, elem_c, val_c));
        }
        self.scopes.pop();
        s.push_str("    }\n");
        s.push_str("  } else if (_it.type == HN_DICT) {\n");
        s.push_str("    for (int _i = 0; _i < _it.as.dict->len; _i++) {\n");
        s.push_str(&format!("      hn_free_value({});\n", vv));
        s.push_str(&format!("      {} = hn_str(_it.as.dict->keys[_i]);\n", vv));
        if var2.is_some() {
            s.push_str(&format!("      hn_free_value({});\n", vv2));
            s.push_str(&format!("      {} = hn_copy(_it.as.dict->vals[_i]);\n", vv2));
        }
        self.scopes.push(HashMap::new());
        self.scopes.last_mut().expect("scope").insert(var.to_string(), vv.clone());
        if let Some(v2) = var2 {
            self.scopes.last_mut().expect("scope").insert(v2.clone(), vv2.clone());
        }
        let elem_d = self.gen_expr(elem)?;
        let val_d = match value {
            Some(v) => self.gen_expr(v)?,
            None => String::new(),
        };
        let cond_d = match cond {
            Some(c) => {
                let ce = self.gen_expr(c)?;
                format!("if (hn_truthy({})) ", ce)
            }
            None => String::new(),
        };
        if is_list {
            s.push_str(&format!("      {}hn_list_push(_l, {});\n", cond_d, elem_d));
        } else {
            s.push_str(&format!("      {}hn_dict_set_v(_d, {}, {});\n", cond_d, elem_d, val_d));
        }
        self.scopes.pop();
        s.push_str("    }\n");
        s.push_str("  }\n");
        s.push_str(&format!("  hn_free_value({}); hn_free_value(_it);\n", vv));
        if var2.is_some() {
            s.push_str(&format!("  hn_free_value({});\n", vv2));
        }
        s.push_str(&format!("  {};\n}})", out_name));
        Ok(s)
    }

    /// 函数调用：解析 callee（变量 lambda → 用户函数/类方法 → 结构体构造 → 内置）
    fn gen_call(&mut self, callee: &str, args: &[Expr], span: Span) -> Result<String, ZError> {
        // 先求值参数（自左向右，先入临时数组）
        let mut arg_exprs: Vec<String> = Vec::new();
        for a in args {
            arg_exprs.push(self.gen_expr(a)?);
        }
        let n = arg_exprs.len();

        // 1) 变量名 → lambda 调用
        if let Some(v) = self.lookup(callee) {
            let mut s = String::from("({ ");
            s.push_str(&format!("HnValue _a[{}] = {{ {} }}; ", n, arg_exprs.join(", ")));
            s.push_str(&format!("HnValue _r = hn_call_fn(hn_copy({}), _a, {}); ", v, n));
            for i in 0..n {
                s.push_str(&format!("hn_free_value(_a[{}]); ", i));
            }
            s.push_str("_r; })");
            return Ok(s);
        }

        // 2) 用户函数 / 类方法（"类.方法"）
        if self.fn_lookup(callee).is_some() {
            let slot = self.slot_for(callee);
            let mut s = String::from("({ ");
            s.push_str(&format!("HnValue _a[{}] = {{ {} }}; ", n, arg_exprs.join(", ")));
            s.push_str(&format!("HnValue _r = hn_f{}(_a, {}, NULL, 0); ", slot, n));
            for i in 0..n {
                s.push_str(&format!("hn_free_value(_a[{}]); ", i));
            }
            s.push_str("_r; })");
            return Ok(s);
        }

        // 3) 结构体构造：Name(字段...) → dict
        if let Some(fields) = self.structs.get(callee).cloned() {
            if fields.len() != n {
                return Err(zerr(
                    &self.file,
                    &self.src,
                    codes::ARG_COUNT,
                    format!("结构体 `{}` 需要 {} 个字段，实际传入 {}", callee, fields.len(), n),
                    span,
                    Some("按结构体字段顺序传参"),
                ));
            }
            let mut s = String::from("({ HnValue _d = hn_dict_new();");
            for (i, f) in fields.iter().enumerate() {
                s.push_str(&format!(" hn_dict_set(_d, {}, {});", c_str_lit(f), arg_exprs[i]));
            }
            s.push_str(" _d; })");
            return Ok(s);
        }

        // 4) 内置函数
        if is_aot_builtin(callee) {
            let mut s = String::from("({ ");
            s.push_str(&format!("HnValue _a[{}] = {{ {} }}; ", n, arg_exprs.join(", ")));
            s.push_str(&format!("HnValue _r = hn_call_builtin({}, _a, {}); ", c_str_lit(callee), n));
            for i in 0..n {
                s.push_str(&format!("hn_free_value(_a[{}]); ", i));
            }
            s.push_str("_r; })");
            return Ok(s);
        }

        Err(zerr(
            &self.file,
            &self.src,
            codes::NOT_IMPLEMENTED,
            format!("函数/内置 `{}` 在 AOT 模式暂不支持（未定义或超出核心内置集）", callee),
            span,
            Some("AOT 模式仅支持核心内置；重内置请用解释器运行"),
        ))
    }

    /// lambda 生成：创建闭包值（捕获当前可见变量），并生成 hn_lm<k> 函数
    fn gen_lambda(&mut self, params: &[Param], body: &[Stmt], span: Span) -> Result<String, ZError> {
        let k = self.lambda_counter;
        self.lambda_counter += 1;
        // 捕获列表：当前作用域栈全部可见变量（外→内，内层覆盖外层，去重）
        let mut captured: Vec<(String, String)> = Vec::new(); // (变量名, 闭包内 C 名)
        let mut seen: HashSet<String> = HashSet::new();
        for scope in &self.scopes {
            let mut names: Vec<&String> = scope.keys().collect();
            names.sort();
            for name in names {
                if seen.insert(name.clone()) {
                    captured.push((name.clone(), format!("_c{}", captured.len())));
                }
            }
        }
        // 生成 lambda 函数体（独立作用域：捕获变量 → _cN，参数 → vN）
        let saved_scopes = self.scopes.clone();
        let saved_vc = self.var_counter;
        let saved_tc = self.temp_counter;
        self.scopes.clear();
        self.scopes.push(HashMap::new());
        for (name, cname) in &captured {
            self.scopes
                .last_mut()
                .expect("scope")
                .insert(name.clone(), cname.clone());
        }
        let mut body_c = String::new();
        // 捕获变量副本（每次调用独立，赋值不影响外部——与解释器一致）；先于参数声明（默认值表达式可引用捕获变量）
        for (i, (_, cname)) in captured.iter().enumerate() {
            body_c.push_str(&format!("    HnValue {} = hn_copy(cap[{}]);\n", cname, i));
        }
        for (i, p) in params.iter().enumerate() {
            let vname = format!("v{}", self.var_counter);
            self.var_counter += 1;
            self.scopes
                .last_mut()
                .expect("scope")
                .insert(p.name.clone(), vname.clone());
            let init = match &p.default {
                Some(d) => {
                    let de = self.gen_expr(d)?;
                    format!("(nargs > {} ? hn_copy(args[{}]) : {})", i, i, de)
                }
                None => format!("(nargs > {} ? hn_copy(args[{}]) : hn_null())", i, i),
            };
            body_c.push_str(&format!("    HnValue {} = {};\n", vname, init));
        }
        self.gen_stmts(body, &mut body_c)?;
        body_c.push_str("    return hn_null();\n");
        self.scopes = saved_scopes;
        self.var_counter = saved_vc;
        self.temp_counter = saved_tc;
        // 组装 hn_lm<k>
        let mut text = String::new();
        text.push_str(&format!("static HnValue hn_lm{}(HnValue* args, int nargs, HnValue* cap, int ncap) {{\n", k));
        text.push_str("    (void)ncap;\n");
        text.push_str(&body_c);
        text.push_str("}\n");
        self.lambda_out.push_str(&text);
        // 创建闭包：hn_fn_new(hn_lm<k>, cap 数组, K)
        if captured.is_empty() {
            Ok(format!("hn_fn_new(hn_lm{}, NULL, 0)", k))
        } else {
            let mut s = String::from("({ ");
            s.push_str(&format!("HnValue _cap[{}] = {{ ", captured.len()));
            let mut first = true;
            for (name, _) in &captured {
                let src = self.lookup(name).unwrap_or_else(|| "hn_null()".to_string());
                if !first {
                    s.push_str(", ");
                }
                s.push_str(&format!("hn_copy({})", src));
                first = false;
            }
            s.push_str(&format!(" }}; hn_fn_new(hn_lm{}, _cap, {}); }})", k, captured.len()));
            Ok(s)
        }
    }
}

